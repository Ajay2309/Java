public class relational_operator {
    public static void main(String[] args) {
        int a = 12;
        int b = 10;
        
        boolean result = a<b;
        boolean result1 = a>b;
        
        System.out.println(result);
        System.out.println(result1);

        System.out.println(a<=b);
        System.out.println(a>=b);
        System.out.println(a==b);
        System.out.println(a!=b);

    }
    
}
